import {
  generateContentUniversal,
  SUPPORTED_MODELS,
  type GenerateModelOptions,
  type GenerateModelResult,
} from "@/lib/gemini";
import { DEFAULT_MODEL_ID } from "@/lib/models";
import { reportProviderFailure } from "@/lib/monitoring";

/**
 * Ordered fallback models used when the requested model/provider fails.
 * These are cheap and broadly available so a single outage does not surface to
 * the user as a hard error.
 */
const FALLBACK_MODELS = [
  DEFAULT_MODEL_ID,
  "gemini-1.5-flash-8b",
  "qwen/qwen3.8-27b",
  "@cf/meta/llama-3.1-8b-instruct",
];

function providerOf(modelId: string): string {
  return SUPPORTED_MODELS.find((m) => m.id === modelId)?.provider || "Unknown";
}

/**
 * Server-side AI entry point.
 *
 * 1. Calls the requested model.
 * 2. On failure, logs + notifies the monitor and automatically retries with a
 *    fallback chain so the user still gets an answer.
 * 3. If every candidate fails, throws the last error.
 */
export async function generateAI(
  options: GenerateModelOptions
): Promise<GenerateModelResult> {
  const requested = options.model || DEFAULT_MODEL_ID;

  try {
    return await generateContentUniversal(options);
  } catch (err) {
    reportProviderFailure(providerOf(requested), requested, err);

    // The Auto Smart Router already runs its own internal fallback pipeline.
    if (requested === "auto-router") {
      throw err;
    }

    let lastError = err;
    const candidates = FALLBACK_MODELS.filter((m) => m !== requested);

    for (const candidate of candidates) {
      try {
        const res = await generateContentUniversal({
          ...options,
          model: candidate,
          // Fall back to server-configured keys, not the caller's (possibly bad) key.
          customApiKey: undefined,
        });
        const def = SUPPORTED_MODELS.find((m) => m.id === candidate);
        const note = `> ⚙️ **Auto-recovered**: \`${requested}\` was unavailable, so this reply was generated by **${
          def?.displayName || candidate
        }**.\n\n`;
        return { ...res, text: note + res.text };
      } catch (fallbackErr) {
        lastError = fallbackErr;
        reportProviderFailure(providerOf(candidate), candidate, fallbackErr);
      }
    }

    throw lastError;
  }
}
